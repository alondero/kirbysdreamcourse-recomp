"""Build compact outlines from the Aileron Regular subset bundled with Pillow.
Maintenance tool only. The game draws these contours at the requested size.
"""
from io import BytesIO
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from PIL import ImageFont


class Outline(BasePen):
    def __init__(self, glyphs, units):
        super().__init__(glyphs)
        self.units = units
        self.points = []

    def point(self, p):
        return tuple(round(v * 128 / self.units) for v in p)

    def _moveTo(self, p):
        self.points.append(self.point(p))

    def _lineTo(self, p):
        self.points.append(self.point(p))

    def _qCurveToOne(self, control, end):
        start = self._getCurrentPoint()
        for step in range(1, 7):
            t = step / 6
            self._lineTo(tuple((1-t)**2*a + 2*t*(1-t)*b + t*t*c
                               for a, b, c in zip(start, control, end)))

    def _closePath(self):
        self.points.append((-128, 0))


def main():
    font = TTFont(BytesIO(ImageFont.load_default(32).font_bytes))
    glyphs = font.getGlyphSet()
    units = font["head"].unitsPerEm
    points = []
    metrics = []
    for code in [*range(32, 127), 169]:
        glyph = glyphs[font.getBestCmap()[code]]
        outline = Outline(glyphs, units)
        glyph.draw(outline)
        metrics.append((len(points), len(outline.points), round(glyph.width * 128 / units)))
        points.extend(outline.points)

    lines = ["/* Aileron Regular by Sora Sagano. No Rights Reserved.",
             " * Generated by tools/generate_ui_font.py using Pillow 12.2.0. */",
             "static const int16_t kFontPoints[][2] = {"]
    for i in range(0, len(points), 10):
        lines.append("    " + ", ".join("{%d,%d}" % p for p in points[i:i+10]) + ",")
    lines.extend(["};", "static const struct FontGlyph {",
                  "    uint16_t first, count, advance;", "} kFontGlyphs[] = {"])
    lines.extend("    {%d,%d,%d}," % m for m in metrics)
    lines.append("};")
    target = Path(__file__).resolve().parents[1] / "src/hd_ui_font.inc"
    target.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
